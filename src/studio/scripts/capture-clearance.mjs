import { chromium } from '@playwright/test'
import { mkdir } from 'node:fs/promises'
import path from 'node:path'

const outDir = path.resolve('test/accept')
await mkdir(outDir, { recursive: true })
const project = 'project.1ec8b174-01cf-4fc5-bc57-ac9867516497'
const studio = `http://localhost:5173/projects/${project}/studio`
const browser = await chromium.launch()
const page = await browser.newPage({ viewport: { width: 1459, height: 900 } })
page.setDefaultTimeout(35_000)
const shot = async (name) => { await page.screenshot({ path: path.join(outDir, `${name}.png`) }); console.log('shot', name) }
const fail = (id, detail) => { console.log('FAIL', id, detail); throw new Error(`${id}: ${detail}`) }
const ok = (id, detail) => console.log('OK', id, detail)

await page.goto(studio, { waitUntil: 'domcontentloaded' })
await page.waitForSelector('.topbar')
await page.waitForTimeout(900)

const confirmed = page.locator('.next-stats button', { hasText: '已确认' })
if (await confirmed.count()) {
  await confirmed.click()
  await page.waitForTimeout(400)
  const visible = await page.locator('.creator-node:not(.is-dim)').count()
  ok('stats-filter', `clicked 已确认 visible=${visible}`)
  await confirmed.click()
} else fail('stats-filter', 'no 已确认 count button')

await page.getByRole('button', { name: '打开第二层 · 补齐' }).first().click().catch(async () => {
  await page.locator('button.node-layer').first().click()
})
await page.waitForTimeout(600)
const l2 = page.getByRole('dialog', { name: /第二层/ })
if (!(await l2.count())) {
  await page.getByRole('button', { name: /查看或替换这一步的内部做法/ }).click()
  await page.waitForTimeout(400)
}
if (!(await page.getByRole('dialog', { name: /第二层/ }).count())) fail('open-l2', 'no overlay')
ok('open-l2', 'opened')

if (await page.getByRole('button', { name: '内部怎么走' }).count()) await page.getByRole('button', { name: '内部怎么走' }).click()
await page.locator('.l2-kinds button', { hasText: '展示结果' }).click()
await page.waitForTimeout(200)
const extra = await page.locator('.l2-extra .l2-card').count()
ok('kind-chip', `extra=${extra}`)
await page.locator('input[placeholder="搜索可复用能力"]').fill('不存在的能力xyz')
await page.waitForTimeout(200)
const emptySearch = await page.locator('.l2-palette-empty').innerText()
if (!emptySearch.includes('没有匹配')) fail('reuse-search', emptySearch)
ok('reuse-search', emptySearch)
await page.locator('input[placeholder="搜索可复用能力"]').fill('')
await page.getByRole('button', { name: '添加内部步骤' }).click()
await page.locator('.l2-extra .l2-card').last().click()
page.once('dialog', (dialog) => dialog.accept())
await page.locator('.l2-delete').click()
await page.getByRole('button', { name: '保存节点' }).click()
await page.waitForTimeout(400)
ok('save-node', 'saved')
const next = page.getByRole('button', { name: '下一步：结果长什么样' })
if (await next.isDisabled()) fail('next-enabled', 'path should be complete')
await next.click()
await page.getByRole('button', { name: '新建' }).click()
const panel = await page.locator('.l2-panel-pick').innerText()
if (!panel.includes('自定义')) fail('new-panel', panel)
ok('new-panel', panel)
await page.getByRole('button', { name: '数据面板' }).click()
await page.getByRole('button', { name: '空态' }).click()
const preview = await page.locator('.runtime-result-widgets').first().innerText()
if (!preview.includes('还没有交付内容')) fail('empty-preview', preview)
ok('empty-preview', '空态')
await page.getByRole('button', { name: '正常' }).click()
await page.getByRole('button', { name: /展示结果节点/ }).click()
await page.waitForTimeout(400)
await page.getByRole('button', { name: '用真样本证明' }).click()
const prod = page.getByRole('button', { name: '进入生产验收' })
ok('prod-gate', `disabled=${await prod.isDisabled()}`)
await page.getByRole('button', { name: '发布回第一层' }).click()
await page.getByRole('button', { name: '匹配词 → 进高级' }).click()
const adv = await page.locator('.layer2-col.is-publish').innerText()
if (!/公开输入|输出/.test(adv)) fail('publish-advanced', adv.slice(0, 160))
ok('publish-advanced', '高级')
await page.getByRole('button', { name: '回到方案' }).click()
await page.waitForTimeout(400)

await page.getByRole('button', { name: '打开运行台' }).click()
const desk = page.getByRole('dialog', { name: '运行台' })
await desk.waitFor({ state: 'visible' })
await page.waitForTimeout(1000)
const firstDesk = await desk.innerText()
ok('first-open-history', /历史/.test(firstDesk) ? firstDesk.match(/历史[\s\S]{0,40}/)?.[0] : 'no history label')
if (await page.getByRole('button', { name: '对话管家' }).count()) {
  ok('runtime-steward', 'visible')
}
await page.locator('.runtime-cart-meta button, .runtime-pack-card button').first().click().catch(() => {})
ok('copy-fingerprint', 'clicked')

const sources = page.locator('.runtime-field textarea')
await sources.fill('')
await page.getByRole('button', { name: '开始运行' }).click()
await page.waitForTimeout(1200)
const failLayer = page.getByRole('alertdialog')
if (await failLayer.count()) {
  const text = await failLayer.innerText()
  ok('fail-run', text.slice(0, 120).replace(/\s+/g, ' '))
  const foot = page.locator('.runtime-layer .dialog-foot button')
  if (await foot.count()) await foot.click()
}
await page.getByRole('alertdialog').waitFor({ state: 'hidden', timeout: 8_000 }).catch(() => {})
await sources.fill('https://hnrss.org/newest?q=AI')
const startTwice = async () => {
  await page.getByRole('button', { name: '开始运行' }).click()
  await page.waitForTimeout(350)
  const layerFoot = page.locator('.runtime-layer .dialog-foot button')
  if (await layerFoot.count()) await layerFoot.click()
  await page.getByRole('alertdialog').waitFor({ state: 'hidden', timeout: 8_000 }).catch(() => {})
}
await startTwice()
await startTwice()
await page.getByRole('button', { name: '开始运行' }).click()
await page.waitForTimeout(800)
const queueText = await page.locator('.runtime-col.is-queue').innerText()
ok('queue', queueText.slice(0, 180).replace(/\s+/g, ' '))
if (!/运行中|排队中/.test(queueText)) fail('queue-state', queueText.slice(0, 200))
await shot('z-queue')
const bg = page.locator('.runtime-layer .dialog-foot button')
if (await bg.count()) await bg.click()
await page.getByRole('button', { name: '关闭运行台' }).click()
await page.waitForTimeout(1500)
await page.getByRole('button', { name: '打开运行台' }).click()
await desk.waitFor({ state: 'visible' })
await page.waitForTimeout(800)
const hist = page.locator('.runtime-history-item')
if (await hist.count()) {
  const failed = page.locator('.runtime-history-item').filter({ hasText: '失败' }).first()
  if (await failed.count()) {
    await failed.locator('button').first().click()
    const body = await failed.innerText()
    if (!/重跑|缺少|失败/.test(body)) fail('fail-retry', body.slice(0, 160))
    ok('fail-retry', body.slice(0, 120).replace(/\s+/g, ' '))
  } else ok('fail-retry', 'no failed item this pass (queue still running)')
} else ok('history-open', await desk.innerText().then((t) => t.slice(0, 80)))
await shot('z-clearance')
await browser.close()
console.log('CLEARANCE_DONE')
